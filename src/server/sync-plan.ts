import type { ProgramDocument, SyncEventRef } from '../shared/types.ts'

/** The fields this app owns on a calendar event. Everything else is left alone. */
export interface DesiredEvent {
  date: string
  endDate: string
  summary: string
  description: string
}

/** The subset of a Google Calendar event the planner needs. */
export interface RemoteEvent {
  id: string
  summary?: string | null
  description?: string | null
  startDate?: string | null
  endDate?: string | null
}

export interface SyncPlan {
  inserts: DesiredEvent[]
  updates: { eventId: string; body: DesiredEvent }[]
  unchanged: { eventId: string; date: string }[]
  deletes: RemoteEvent[]
}

function sameEvent(remote: RemoteEvent, body: DesiredEvent): boolean {
  return (
    (remote.summary ?? '') === body.summary &&
    (remote.description ?? '') === body.description &&
    remote.startDate === body.date &&
    remote.endDate === body.endDate
  )
}

/**
 * Reconcile the program's sessions against the events currently on the
 * calendar. Matching is by session date; within a date, an event recorded in
 * the previous sync state wins (so ours keep their IDs), otherwise the first
 * event on that date is reused.
 */
export function planSync(
  desired: DesiredEvent[],
  remote: RemoteEvent[],
  prevRefs: SyncEventRef[] = [],
): SyncPlan {
  const byDate = new Map<string, RemoteEvent[]>()
  for (const ev of remote) {
    if (!ev.startDate) continue
    const list = byDate.get(ev.startDate) ?? []
    list.push(ev)
    byDate.set(ev.startDate, list)
  }

  const knownIds = new Set(prevRefs.map((r) => r.eventId))
  const preferred = new Map<string, string[]>()
  for (const ref of prevRefs) {
    const list = preferred.get(ref.date) ?? []
    list.push(ref.eventId)
    preferred.set(ref.date, list)
  }

  const used = new Set<string>()
  const inserts: DesiredEvent[] = []
  const updates: SyncPlan['updates'] = []
  const unchanged: SyncPlan['unchanged'] = []

  for (const body of desired) {
    const candidates = (byDate.get(body.date) ?? []).filter((ev) => !used.has(ev.id))
    const wanted = preferred.get(body.date) ?? []
    const match =
      candidates.find((ev) => wanted.includes(ev.id)) ?? candidates[0] ?? null

    if (!match) {
      inserts.push(body)
      continue
    }
    used.add(match.id)
    if (sameEvent(match, body)) unchanged.push({ eventId: match.id, date: body.date })
    else updates.push({ eventId: match.id, body })
  }

  // Remove leftovers only when they are ours: generated by this app (🏋️
  // prefix) or recorded in the previous sync state. Hand-made events the user
  // added to the calendar are never deleted.
  const deletes = remote.filter(
    (ev) => !used.has(ev.id) && ((ev.summary ?? '').startsWith('🏋️') || knownIds.has(ev.id)),
  )

  return { inserts, updates, unchanged, deletes }
}

/** Build the desired event bodies for a program, in session order. */
export function desiredEvents(
  doc: ProgramDocument,
  summaryFor: (title: string) => string,
  descriptionFor: (session: ProgramDocument['sessions'][number]) => string,
  nextDay: (date: string) => string,
): DesiredEvent[] {
  return doc.sessions.map((session) => ({
    date: session.date,
    endDate: nextDay(session.date),
    summary: summaryFor(session.title),
    description: descriptionFor(session),
  }))
}
